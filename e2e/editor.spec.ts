import { expect, test, type Page } from '@playwright/test'
import legacy from '../src/lib/fixtures/legacy-basic.json' with { type: 'json' }

const canvas = (page: Page) => page.frameLocator('.gjs-frame')
async function openEditor(page: Page) {
  await page.goto('/editor/new?template=blog')
  await expect(page.locator('.grapes-workbench')).toBeVisible()
  await expect(canvas(page).locator('h1')).toBeVisible()
  await expect(page.getByText('Todas as alterações salvas.', { exact: true })).toBeVisible()
}
async function editTitle(page: Page, title: string) {
  const heading = canvas(page).locator('h1')
  await heading.dblclick()
  await expect(canvas(page).locator('[contenteditable="true"]')).toBeVisible()
  await canvas(page).locator('[contenteditable="true"]').fill(title)
  await page.getByLabel('Assunto da newsletter').click()
}
test('edição real, prévia, autosave e reabertura', async ({ page }) => {
  await openEditor(page)
  await editTitle(page, 'Uma frase que não pode sumir.')
  await page.getByLabel('Assunto da newsletter').fill('Rascunho de estabilidade')
  await page.getByRole('button', { name: 'Revisar edição', exact: true }).click()
  await expect(page.frameLocator('iframe[title="Prévia da edição"]').getByText('Uma frase que não pode sumir.')).toBeVisible()
  await page.reload()
  await expect(canvas(page).locator('h1')).toHaveText('Uma frase que não pode sumir.')
  await expect(page.getByLabel('Assunto da newsletter')).toHaveValue('Rascunho de estabilidade')
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('mais-um-cafezinho:drafts:v1') || '[]')[0])
  expect(saved.schemaVersion).toBe(3)
  expect(saved.document.type).toBe('grapesjs')
})
