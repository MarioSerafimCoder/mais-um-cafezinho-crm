test('editor e templates mantêm espaço de escrita em desktop e mobile', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await openEditor(page)
  await expect(page.locator('.tiptap h1')).toBeVisible()
  await page.screenshot({ path: 'logs/phase2-editor-desktop.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
  await page.screenshot({ path: 'logs/phase2-editor-mobile.png' })
  await page.getByRole('button', { name: 'Prévia', exact: true }).click()
  await page.getByRole('button', { name: 'Celular', exact: true }).click()
  await expect.poll(async () => page.frameLocator('iframe[title="Prévia da newsletter"]').locator('html').evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.getByRole('button', { name: 'Salvar local', exact: true }).click()
  await page.goto('/templates')
  await expect(page.locator('iframe[title^="Prévia real:"]')).toHaveCount(3)
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
})
